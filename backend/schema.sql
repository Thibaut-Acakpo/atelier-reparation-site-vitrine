-- =============================================================================
-- Schéma PostgreSQL — plateforme multi-ateliers (un site vitrine + une gestion
-- par client). Ce fichier est IDEMPOTENT : il peut être rejoué sans risque.
-- Il est exécuté automatiquement par `npm run migrate` (et au démarrage de
-- l'API via `npm start`).
--
-- Principe : chaque donnée métier porte un `atelier_id`. Toutes les requêtes
-- de l'API filtrent sur cette colonne ; un client ne voit jamais les données
-- d'un autre.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Ateliers (= clients du développeur) et comptes développeur
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ateliers (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom         text NOT NULL,
  slug        text NOT NULL UNIQUE,
  domaine     text UNIQUE,
  logo_url    text,
  actif       integer NOT NULL DEFAULT 1,
  created_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS developer_accounts (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom                 text NOT NULL,
  email               text NOT NULL UNIQUE,
  mot_de_passe_hash   text NOT NULL,
  actif               integer NOT NULL DEFAULT 1,
  derniere_connexion  timestamp,
  created_at          timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------------
-- Données globales (communes à tous les ateliers)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS statuts_reparation (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code    text NOT NULL UNIQUE,
  libelle text NOT NULL,
  ordre   integer NOT NULL
);

-- ---------------------------------------------------------------------------
-- Données propres à chaque atelier
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS admins (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id          integer REFERENCES ateliers(id) ON DELETE CASCADE,
  nom                 text NOT NULL,
  email               text NOT NULL UNIQUE,
  mot_de_passe_hash   text NOT NULL,
  role                text NOT NULL DEFAULT 'technicien',
  actif               integer NOT NULL DEFAULT 1,
  derniere_connexion  timestamp,
  created_at          timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS settings (
  atelier_id integer NOT NULL REFERENCES ateliers(id) ON DELETE CASCADE,
  cle        text NOT NULL,
  valeur     text,
  PRIMARY KEY (atelier_id, cle)
);

CREATE TABLE IF NOT EXISTS services (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  titre       text NOT NULL,
  description text NOT NULL DEFAULT '',
  icone       text,
  ordre       integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS categories_appareils (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  code        text NOT NULL,
  titre       text NOT NULL,
  description text NOT NULL DEFAULT '',
  icone       text,
  ordre       integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS faq (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  question    text NOT NULL,
  reponse     text NOT NULL DEFAULT '',
  ordre       integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS realisations (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id    integer REFERENCES ateliers(id) ON DELETE CASCADE,
  titre         text NOT NULL,
  type_appareil text NOT NULL,
  marque        text,
  modele        text,
  probleme      text NOT NULL,
  intervention  text NOT NULL,
  image_avant   text,
  image_apres   text,
  publie        integer NOT NULL DEFAULT 1,
  created_at    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS avis (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  nom         text NOT NULL,
  note        integer NOT NULL CHECK (note >= 1 AND note <= 5),
  commentaire text NOT NULL,
  statut      text NOT NULL DEFAULT 'en_attente'
              CHECK (statut IN ('en_attente', 'valide', 'refuse')),
  created_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contacts (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  nom         text NOT NULL,
  email       text,
  telephone   text,
  sujet       text,
  message     text NOT NULL,
  traite      integer NOT NULL DEFAULT 0,
  created_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clients (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  nom_complet text NOT NULL,
  telephone   text NOT NULL,
  email       text,
  created_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS appareils (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  client_id   integer REFERENCES clients(id) ON DELETE CASCADE,
  type        text NOT NULL,
  marque      text NOT NULL,
  modele      text NOT NULL,
  created_at  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS demandes_reparation (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id               integer REFERENCES ateliers(id) ON DELETE CASCADE,
  client_id                integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  appareil_id              integer NOT NULL REFERENCES appareils(id) ON DELETE CASCADE,
  panne                    text NOT NULL,
  photo_path               text,
  date_souhaitee           text NOT NULL,
  heure_souhaitee          text NOT NULL,
  confidentialite_acceptee integer NOT NULL DEFAULT 0,
  statut_traitement        text NOT NULL DEFAULT 'nouvelle',
  created_at               timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rendez_vous (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id      integer REFERENCES ateliers(id) ON DELETE CASCADE,
  client_id       integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  date_souhaitee  text NOT NULL,
  heure_souhaitee text NOT NULL,
  motif           text,
  statut          text NOT NULL DEFAULT 'en_attente'
                  CHECK (statut IN ('en_attente', 'confirme', 'modifie', 'refuse')),
  created_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pieces (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id  integer REFERENCES ateliers(id) ON DELETE CASCADE,
  nom         text NOT NULL,
  reference   text
);

CREATE TABLE IF NOT EXISTS reparations (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id               integer REFERENCES ateliers(id) ON DELETE CASCADE,
  numero_fiche             text NOT NULL UNIQUE,
  code_public              text NOT NULL UNIQUE,
  client_id                integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  appareil_id              integer NOT NULL REFERENCES appareils(id) ON DELETE CASCADE,
  demande_id               integer REFERENCES demandes_reparation(id) ON DELETE SET NULL,
  statut_id                integer NOT NULL REFERENCES statuts_reparation(id),
  description_statut       text,
  diagnostic               text,
  cout                     numeric,
  date_estimee_recuperation text,
  visible_publiquement     integer NOT NULL DEFAULT 1,
  devis_decision           text NOT NULL DEFAULT 'en_attente'
                           CHECK (devis_decision IN ('en_attente', 'accepte', 'refuse')),
  devis_decision_date      text,
  created_at               timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at               timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS historique_reparation (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reparation_id integer NOT NULL REFERENCES reparations(id) ON DELETE CASCADE,
  statut_id     integer NOT NULL REFERENCES statuts_reparation(id),
  commentaire   text,
  created_at    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reparation_pieces (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reparation_id integer NOT NULL REFERENCES reparations(id) ON DELETE CASCADE,
  piece_id      integer NOT NULL REFERENCES pieces(id) ON DELETE CASCADE,
  quantite      integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS notifications (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atelier_id     integer REFERENCES ateliers(id) ON DELETE CASCADE,
  type           text NOT NULL,
  destinataire   text,
  contenu_resume text,
  statut         text NOT NULL DEFAULT 'a_envoyer',
  created_at     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
